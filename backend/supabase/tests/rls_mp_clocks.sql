-- Tests multiplayer chess clocks (migration 029). Users: u1 white/creator, u2 black, u3 outsider, plus anon.
-- Time cannot be waited on inside a rolled-back test, so clock_started_at is moved back with a superuser update.
-- Known gap: the final "untimed claim" check is refused with 'Game not found' (u2 is not in that game), so the
-- 'The clock is not running' branch is not exercised here. Rolled back; non-destructive. Expected output in comments.
do $$
declare
  u1 uuid := gen_random_uuid(); u2 uuid := gen_random_uuid(); u3 uuid := gen_random_uuid();
  g uuid; gu uuid; code text; r text[] := '{}'; row public.mp_games%rowtype; ret int; rm uuid;
begin
  insert into auth.users (id, email) values (u1,'ck-1@test.invalid'),(u2,'ck-2@test.invalid'),(u3,'ck-3@test.invalid');
  perform set_config('request.jwt.claims', json_build_object('sub',u1,'role','authenticated')::text, true);
  set local role authenticated;
  begin perform public.mp_create('white', 0, 0); r := array_append(r,'FAIL 0 minutes accepted');
  exception when others then r := array_append(r,'0 minutes blocked OK'); end;
  begin perform public.mp_create('white', 5, 61); r := array_append(r,'FAIL 61s increment accepted');
  exception when others then r := array_append(r,'61s increment blocked OK'); end;
  select c.id, c.invite_code into g, code from public.mp_create('white', 5, 3) c;
  select * into row from public.mp_games where id = g;
  r := array_append(r,'initial ms=' || row.white_ms || '/' || row.black_ms || ' inc=' || row.clock_increment || ' (expect 300000/300000 inc=3)');
  select c.id into gu from public.mp_create('white') c;
  select * into row from public.mp_games where id = gu;
  r := array_append(r,'untimed game has null clock=' || (row.clock_seconds is null and row.white_ms is null) || ' (expect true)');
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub',u2,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_join(code);
  reset role;
  update public.mp_games set clock_started_at = now() - interval '1 hour' where id = g;
  perform set_config('request.jwt.claims', json_build_object('sub',u1,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_move(g, 0, 'e2e4');
  reset role;
  update public.mp_games set clock_started_at = now() - interval '1 hour' where id = g;
  perform set_config('request.jwt.claims', json_build_object('sub',u2,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_move(g, 1, 'e7e5');
  select * into row from public.mp_games where id = g;
  r := array_append(r,'after free first moves ms=' || row.white_ms || '/' || row.black_ms || ' (expect 300000/300000)');
  begin perform public.mp_claim_timeout(g); r := array_append(r,'FAIL early claim accepted');
  exception when others then r := array_append(r,'early claim refused: ' || left(sqlerrm,45)); end;
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub',u3,'role','authenticated')::text, true);
  set local role authenticated;
  begin perform public.mp_claim_timeout(g); r := array_append(r,'FAIL outsider claimed');
  exception when others then r := array_append(r,'outsider claim blocked OK'); end;
  reset role;
  update public.mp_games set clock_started_at = now() - interval '10 seconds' where id = g;
  perform set_config('request.jwt.claims', json_build_object('sub',u1,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_move(g, 2, 'g1f3');
  select * into row from public.mp_games where id = g;
  r := array_append(r,'white ms after 10s+3s inc=' || row.white_ms || ' (expect 293000, black untouched ' || row.black_ms || ')');
  begin perform public.mp_claim_timeout(g); r := array_append(r,'FAIL claim before expiry');
  exception when others then r := array_append(r,'u1 early claim: ' || left(sqlerrm,40)); end;
  reset role;
  update public.mp_games set clock_started_at = now() - interval '6 minutes' where id = g;
  perform set_config('request.jwt.claims', json_build_object('sub',u2,'role','authenticated')::text, true);
  set local role authenticated;
  begin perform public.mp_claim_timeout(g); r := array_append(r,'FAIL slow player claimed own clock');
  exception when others then r := array_append(r,'cannot claim on own clock OK'); end;
  ret := public.mp_move(g, 3, 'b8c6');
  select * into row from public.mp_games where id = g;
  r := array_append(r,'late move: status=' || row.status || ' timed_out_by_black=' || (row.timed_out_by = u2) || ' moves=' || cardinality(row.moves) || ' ret=' || ret || ' (expect timeout, true, 3, 3)');
  begin perform public.mp_resign(g); r := array_append(r,'FAIL resign after timeout');
  exception when others then r := array_append(r,'resign after timeout blocked OK'); end;
  rm := public.mp_rematch(g);
  select * into row from public.mp_games where id = rm;
  r := array_append(r,'rematch clock=' || row.clock_seconds || '+' || row.clock_increment || ' ms=' || row.white_ms || ' (expect 300+3 300000)');
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub',u1,'role','authenticated')::text, true);
  set local role authenticated;
  select c.id, c.invite_code into g, code from public.mp_create('white', 1, 0) c;
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub',u2,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_join(code);
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub',u1,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_move(g, 0, 'e2e4');
  reset role;
  perform set_config('request.jwt.claims', json_build_object('sub',u2,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_move(g, 1, 'e7e5');
  begin perform public.mp_claim_timeout(g); r := array_append(r,'FAIL claim before expiry');
  exception when others then r := array_append(r,'early claim refused: ' || left(sqlerrm,40)); end;
  reset role;
  update public.mp_games set clock_started_at = now() - interval '2 minutes' where id = g;
  perform set_config('request.jwt.claims', json_build_object('sub',u2,'role','authenticated')::text, true);
  set local role authenticated;
  perform public.mp_claim_timeout(g);
  select * into row from public.mp_games where id = g;
  r := array_append(r,'claim: status=' || row.status || ' timed_out_by_white=' || (row.timed_out_by = u1) || ' (expect timeout, true)');
  begin perform public.mp_claim_timeout(gu); r := array_append(r,'FAIL claim on untimed');
  exception when others then r := array_append(r,'untimed claim refused: ' || left(sqlerrm,30)); end;
  reset role;
  perform set_config('request.jwt.claims','{}', true);
  set local role anon;
  begin perform public.mp_claim_timeout(g); r := array_append(r,'FAIL anon claim');
  exception when others then r := array_append(r,'anon claim blocked OK'); end;
  reset role;
  raise exception 'RESULTS: %', array_to_string(r, E'\n');
end $$;
